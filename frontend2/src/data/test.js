// Generate an instant 4-sentence Test Game for any word
export async function getQuestionData(word, lang = "english") {
    const detailed = DETAILED_WORDS[word];
    const senses = TAMIL_WORDS[word] || ["meaning 1", "meaning 2", "meaning 3", "meaning 4"];
    
    // Pick exactly 4 senses for options
    let chosenSenses = [];
    if (detailed) {
        chosenSenses = detailed.meanings.map(m => m.english_label || m.meaning);
    } else {
        if (senses.length >= 4) {
            chosenSenses = senses.slice(0, 4);
        } else {
            chosenSenses = [...senses, "Alternate 1", "Alternate 2", "Alternate 3"].slice(0, 4);
        }
    }

    const quizSentences = chosenSenses.map((sense, i) => {
        const letters = ["A", "B", "C", "D"];
        const custom = detailed?.meanings.find(m => (m.english_label || m.meaning) === sense);
        
        return {
            id: letters[i],
            tamil: custom?.sentence || `This sentence demonstrates ${word} as ${sense}.`,
            english: custom?.translation || `(Translation: ${sense})`,
            correct_meaning: custom?.quiz_options ? custom.quiz_options[0] : sense,
            quiz_options: custom?.quiz_options || [sense, "Wrong 1", "Wrong 2", "Wrong 3"]
        };
    });

    // We take the first sentence's options for now if we want to show it in the UI, 
    // but the options vary per sentence now.
    const firstQuiz = quizSentences[0];

    return {
        word,
        thirukkural: detailed?.thirukkural,
        thirukkural_translation: detailed?.thirukkural_translation,
        sentences: quizSentences,
        options: firstQuiz.quiz_options.map(s => ({ label: s })).sort(() => Math.random() - 0.5)
    };
}

// Generate instant semantic data mapping for the Mind Map
export async function getSemanticData(word) {
    const detailed = DETAILED_WORDS[word];
    const senses = TAMIL_WORDS[word] || ["meaning"];
    
    const results = detailed ? detailed.meanings.map(m => ({
        label: m.english_label || m.meaning,
        translation: m.translation,
        sentence: m.sentence
    })) : senses.map(s => ({
        label: s,
        translation: "Sample translation",
        sentence: `Sample sentence for ${s}`
    }));

    return {
        word,
        transliteration: detailed?.transliteration || "...",
        senses: results.slice(0, 4) // Mind Map only supports 4 for the cross layout
    };
}

